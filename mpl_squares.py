import matplotlib.pyplot as plt #导入pyplot模块,指定别名为plt

squares = [1, 4, 9, 16, 25] #创建一个列表，包含前五个整数的平方
    # 这是一个 Python 列表，存储了 1²、2²、3²、4²、5² 的结果。
    # 关键概念（数据映射）：
    #   当你只传入一个列表 squares 时，Matplotlib 会自动生成 x 轴数据，默认从 0 开始。
    #   即：x = [0, 1, 2, 3, 4]，y = [1, 4, 9, 16, 25]。
    # 所以第一个点坐标是 (0, 1)，而不是你直觉中的 (1, 1)。

# 创建画布与坐标系
fig, ax = plt.subplots() 
    # 创建 Figure（画布/窗口）：相当于一张空白的纸，返回给 fig。
    # 创建 Axes（坐标系/子图）：相当于在纸上画了一个坐标系，返回给 ax。

# 绘制折线图
ax.plot(squares) #在子图上绘制平方数的折线图
    #绘图逻辑：
    #   将 squares 作为 y 轴数据。
    #   x 轴自动取 range(len(squares))（即 0,1,2,3,4）。
    #   默认绘制为蓝色实线（除非你修改样式参数，如 color='red' 或 linestyle='--'）。
    #   画出来的点连线顺序：(0,1) -> (1,4) -> (2,9) -> (3,16) -> (4,25)

#显示图形
plt.show() 
